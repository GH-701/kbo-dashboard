def fetch_kbo_standings() -> List[Dict[str, Any]]:
    """
    KBO 공식 홈페이지에서 실시간 리그 순위표를 크롤링
    """
    url = "https://www.koreabaseball.com/Record/TeamRank/TeamRankDaily.aspx"
    try:
        res = requests.get(url, headers=DEFAULT_HEADERS, timeout=8)
        if res.status_code == 200:
            soup = BeautifulSoup(res.text, 'html.parser')
            table = soup.find('table', {'class': 'tData'})
            if table and table.find('tbody'):
                standings = []
                for row in table.find('tbody').find_all('tr'):
                    cols = [td.get_text(strip=True) for td in row.find_all('td')]
                    if len(cols) >= 12:
                        team_raw = cols[1]
                        team_key = resolve_team_key(team_raw) or team_raw
                        color = KBO_TEAMS.get(team_key, {}).get("color_primary", "#333333")
                        standings.append({
                            "순위": cols[0],
                            "팀명": team_key,
                            "경기": cols[2],
                            "승": cols[3],
                            "패": cols[4],
                            "무": cols[5],
                            "승률": cols[6],
                            "게임차": cols[7],
                            "최근10경기": cols[8],
                            "연속": cols[9],
                            "홈": cols[10],
                            "방문": cols[11],
                            "color": color
                        })
                if standings:
                    return standings
    except Exception as e:
        print(f"[WARN] fetch_kbo_standings error: {e}")

    # fallback 반환
    result = []
    for item in FALLBACK_STANDINGS:
        d = dict(item)
        d["color"] = KBO_TEAMS.get(d["팀명"], {}).get("color_primary", "#333333")
        result.append(d)
    return result

def fetch_kbo_news(query: str = "KBO 프로야구") -> List[Dict[str, str]]:
    """
    다음 뉴스 검색을 통해 실시간 KBO 주요 야구 뉴스를 크롤링
    """
    encoded_query = requests.utils.quote(query)
    url = f"https://search.daum.net/search?w=news&q={encoded_query}&sort=recency"
    articles = []
    try:
        res = requests.get(url, headers=DEFAULT_HEADERS, timeout=8)
        if res.status_code == 200:
            soup = BeautifulSoup(res.text, 'html.parser')
            items = soup.select('.c-item-content')
            for it in items:
                title_el = it.select_one('.item-title a')
                press_el = it.select_one('.item-sub .txt_info') or it.select_one('.sub_info')
                time_el = it.select_one('.item-sub .txt_time') or it.select_one('.txt_date')
                desc_el = it.select_one('.item-contents') or it.select_one('.conts_desc')
                thumb_el = it.select_one('.item-thumb img') or it.select_one('img')

                if title_el:
                    title = title_el.get_text(strip=True)
                    link = title_el.get('href', '#')
                    press = press_el.get_text(strip=True) if press_el else "야구뉴스"
                    time_str = time_el.get_text(strip=True) if time_el else ""
                    desc = desc_el.get_text(strip=True) if desc_el else ""
                    thumb = thumb_el.get('src', '') if thumb_el else ""

                    articles.append({
                        "title": title,
                        "link": link,
                        "press": press,
                        "time": time_str,
                        "desc": desc,
                        "image": thumb
                    })
                if len(articles) >= 15:
                    break
    except Exception as e:
        print(f"[WARN] fetch_kbo_news error: {e}")

    # 최소 안전 반환 뉴스
    if not articles:
        articles.append({
            "title": "KBO 리그 최신 소식 및 스프링캠프/스토브리그 동향",
            "link": "https://www.koreabaseball.com/News/Notice/List.aspx",
            "press": "KBO 공식",
            "time": "실시간",
            "desc": "2026 KBO 리그 정규시즌 및 구단별 전력 보강 소식을 확인하세요.",
            "image": ""
        })
    return articles

